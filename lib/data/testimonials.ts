export function getFeaturedTestimonials(count: number = 6): Testimonial[] {
  return testimonials.filter((t) => t.rating >= 5).slice(0, count)
}

export function getTestimonialsByService(service: string): Testimonial[] {
  return testimonials.filter(
    (t) => t.service?.toLowerCase() === service.toLowerCase()
  )
}

export function getTestimonialsByDoctor(doctorName: string): Testimonial[] {
  return testimonials.filter(
    (t) => t.doctorName?.toLowerCase() === doctorName.toLowerCase()
  )
}
