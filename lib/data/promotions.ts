export function getPromotionBySlug(slug: string): Promotion | undefined {
  return promotions.find((promo) => promo.slug === slug)
}

export function getActivePromotions(): Promotion[] {
  const today = new Date()
  return promotions.filter((promo) => {
    const validUntil = new Date(promo.validUntil)
    return promo.isActive && validUntil >= today
  })
}

export function getPromotionsByCategory(category: string): Promotion[] {
  return promotions.filter(
    (promo) => promo.category.toLowerCase() === category.toLowerCase()
  )
}

export function getFeaturedPromotions(count: number = 3): Promotion[] {
  return getActivePromotions().slice(0, count)
}
